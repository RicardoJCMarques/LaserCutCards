/*
 * Authoring contract for every path in this file:
 *  - Normalized unit box: x and y in [0,1], y increases downward.
 *  - Path data is absolute and limited to M L C S Q T Z. No arcs, no relative
 *    commands, no H/V. transformPathData() rejects anything else, and
 *    validateGlyphSet() in art.js runs that same check up front.
 *  - Closed subpaths that never overlap, filled with fill-rule="nonzero". A
 *    counter is a subpath inside the outline, wound against it. LightBurn
 *    fills even-odd whatever the file says, so an overlap would engrave as a hole.
 * Inkscape: set path data output to absolute coordinates and flatten transforms
 * before copying `d` out.
 */

